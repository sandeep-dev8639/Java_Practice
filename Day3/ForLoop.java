public class ForLoop {
    public static void main(String[] args) {
        for (int i = 1; i < 10; i++) {
            System.out.println("hello " + i);
        }

        System.out.println("**********");

        for(int j=5; j>0; j--){
            System.out.println("hi " + j);
        }
    }
}
